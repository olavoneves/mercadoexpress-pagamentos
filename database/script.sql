-- ---------------------------------------------------------------------
-- 1) LIMPEZA (idempotente: pode rodar quantas vezes quiser)
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS TDS_EMAILS_MERCADO;
DROP TABLE IF EXISTS TDS_ITENS_COMPRA_MERCADO;
DROP TABLE IF EXISTS TDS_COMPRAS_MERCADO;
DROP TABLE IF EXISTS TDS_PRODUTOS_MERCADO;

-- ---------------------------------------------------------------------
-- 2) PRODUTOS - entidade da Parte I + PRECO_CUSTO e ESTOQUE_MINIMO
-- ---------------------------------------------------------------------
CREATE TABLE TDS_PRODUTOS_MERCADO (
    ID              BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    NOME            VARCHAR(100)   NOT NULL,
    TIPO            VARCHAR(50)    NOT NULL,
    SETOR           VARCHAR(50)    NOT NULL,
    TAMANHO         VARCHAR(30),
    PRECO_VENDA     NUMERIC(10,2)  NOT NULL,
    PRECO_CUSTO     NUMERIC(10,2)  NOT NULL,
    DESCRICAO       VARCHAR(500),
    ESTOQUE         INTEGER        NOT NULL DEFAULT 0,
    ESTOQUE_MINIMO  INTEGER        NOT NULL DEFAULT 10,
    ATIVO           BOOLEAN        NOT NULL DEFAULT TRUE,
    DATA_CADASTRO   DATE           NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT PK_TDS_PRODUTOS            PRIMARY KEY (ID),
    CONSTRAINT CK_TDS_PRODUTOS_VENDA      CHECK (PRECO_VENDA > 0),
    CONSTRAINT CK_TDS_PRODUTOS_CUSTO      CHECK (PRECO_CUSTO >= 0),
    CONSTRAINT CK_TDS_PRODUTOS_ESTOQUE    CHECK (ESTOQUE >= 0),
    CONSTRAINT CK_TDS_PRODUTOS_MINIMO     CHECK (ESTOQUE_MINIMO >= 0)
);

COMMENT ON TABLE  TDS_PRODUTOS_MERCADO                IS 'Produtos da vitrine do Mercado Express';
COMMENT ON COLUMN TDS_PRODUTOS_MERCADO.PRECO_VENDA    IS 'Preco cobrado do cliente (era PRECO na Parte I)';
COMMENT ON COLUMN TDS_PRODUTOS_MERCADO.PRECO_CUSTO    IS 'Preco pago ao fornecedor; base do calculo de lucro do dashboard';
COMMENT ON COLUMN TDS_PRODUTOS_MERCADO.ESTOQUE        IS 'Quantidade disponivel; baixada quando o pagamento e aprovado';
COMMENT ON COLUMN TDS_PRODUTOS_MERCADO.ESTOQUE_MINIMO IS 'Abaixo ou igual a este valor o dashboard mostra alerta de estoque baixo';

-- ---------------------------------------------------------------------
-- 3) COMPRAS - nascem PENDENTE e mudam com a resposta do banco
-- ---------------------------------------------------------------------
CREATE TABLE TDS_COMPRAS_MERCADO (
    ID                  BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    CLIENTE_NOME        VARCHAR(100)   NOT NULL,
    CLIENTE_EMAIL       VARCHAR(120)   NOT NULL,
    CLIENTE_CPF         VARCHAR(14)    NOT NULL,
    CARTAO_FINAL        VARCHAR(4)     NOT NULL,
    VALOR_TOTAL         NUMERIC(12,2)  NOT NULL,
    CUSTO_TOTAL         NUMERIC(12,2)  NOT NULL,
    STATUS              VARCHAR(10)    NOT NULL DEFAULT 'PENDENTE',
    ORIGEM              VARCHAR(10)    NOT NULL DEFAULT 'LOJA',
    CODIGO_AUTORIZACAO  VARCHAR(20),
    MOTIVO              VARCHAR(255),
    TRANSACAO_ID        VARCHAR(40),
    DATA_CRIACAO        TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DATA_ATUALIZACAO    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_TDS_COMPRAS          PRIMARY KEY (ID),
    CONSTRAINT CK_TDS_COMPRAS_STATUS   CHECK (STATUS IN ('PENDENTE', 'APROVADO', 'RECUSADO')),
    CONSTRAINT CK_TDS_COMPRAS_ORIGEM   CHECK (ORIGEM IN ('LOJA', 'API')),
    CONSTRAINT CK_TDS_COMPRAS_VALOR    CHECK (VALOR_TOTAL > 0)
);

COMMENT ON TABLE  TDS_COMPRAS_MERCADO                    IS 'Pedidos do Mercado Express e o resultado do pagamento';
COMMENT ON COLUMN TDS_COMPRAS_MERCADO.CARTAO_FINAL       IS 'Apenas os 4 ultimos digitos: o numero completo nunca e gravado';
COMMENT ON COLUMN TDS_COMPRAS_MERCADO.CUSTO_TOTAL        IS 'Soma do custo dos itens no momento da compra (lucro = valor - custo)';
COMMENT ON COLUMN TDS_COMPRAS_MERCADO.STATUS             IS 'PENDENTE -> APROVADO | RECUSADO (definido pelo Banco Tranquilo)';
COMMENT ON COLUMN TDS_COMPRAS_MERCADO.CODIGO_AUTORIZACAO IS 'Codigo devolvido pelo banco quando aprovado';
COMMENT ON COLUMN TDS_COMPRAS_MERCADO.MOTIVO             IS 'Motivo da recusa ou mensagem de aprovacao do banco';

CREATE INDEX IX_TDS_COMPRAS_STATUS ON TDS_COMPRAS_MERCADO (STATUS);
CREATE INDEX IX_TDS_COMPRAS_DATA   ON TDS_COMPRAS_MERCADO (DATA_CRIACAO);

-- ---------------------------------------------------------------------
-- 4) ITENS DA COMPRA - preco de venda e custo congelados na compra
-- ---------------------------------------------------------------------
CREATE TABLE TDS_ITENS_COMPRA_MERCADO (
    ID              BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    COMPRA_ID       BIGINT         NOT NULL,
    PRODUTO_ID      BIGINT         NOT NULL,
    QUANTIDADE      INTEGER        NOT NULL,
    PRECO_UNITARIO  NUMERIC(10,2)  NOT NULL,
    CUSTO_UNITARIO  NUMERIC(10,2)  NOT NULL,
    SUBTOTAL        NUMERIC(12,2)  NOT NULL,
    CONSTRAINT PK_TDS_ITENS          PRIMARY KEY (ID),
    CONSTRAINT FK_TDS_ITENS_COMPRA   FOREIGN KEY (COMPRA_ID)  REFERENCES TDS_COMPRAS_MERCADO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_TDS_ITENS_PRODUTO  FOREIGN KEY (PRODUTO_ID) REFERENCES TDS_PRODUTOS_MERCADO (ID),
    CONSTRAINT CK_TDS_ITENS_QTD      CHECK (QUANTIDADE > 0)
);

CREATE INDEX IX_TDS_ITENS_COMPRA  ON TDS_ITENS_COMPRA_MERCADO (COMPRA_ID);
CREATE INDEX IX_TDS_ITENS_PRODUTO ON TDS_ITENS_COMPRA_MERCADO (PRODUTO_ID);

-- ---------------------------------------------------------------------
-- 5) CONTROLE DE E-MAILS - toda tentativa de envio, com sucesso ou falha
-- ---------------------------------------------------------------------
CREATE TABLE TDS_EMAILS_MERCADO (
    ID            BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    DESTINATARIO  VARCHAR(120)   NOT NULL,
    ASSUNTO       VARCHAR(200)   NOT NULL,
    COMPRA_ID     BIGINT,
    STATUS        VARCHAR(10)    NOT NULL,
    ERRO          VARCHAR(1000),
    DATA_ENVIO    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_TDS_EMAILS         PRIMARY KEY (ID),
    CONSTRAINT FK_TDS_EMAILS_COMPRA  FOREIGN KEY (COMPRA_ID) REFERENCES TDS_COMPRAS_MERCADO (ID) ON DELETE SET NULL,
    CONSTRAINT CK_TDS_EMAILS_STATUS  CHECK (STATUS IN ('ENVIADO', 'FALHA'))
);

COMMENT ON TABLE  TDS_EMAILS_MERCADO        IS 'Registro de todos os e-mails disparados pelo mercado-express';
COMMENT ON COLUMN TDS_EMAILS_MERCADO.STATUS IS 'ENVIADO = aceito pelo SMTP | FALHA = erro registrado em ERRO, fluxo segue';

CREATE INDEX IX_TDS_EMAILS_DATA ON TDS_EMAILS_MERCADO (DATA_ENVIO);

